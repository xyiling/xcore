%include "boot.inc"

[bits 16]
section loader vstart=LOADER_BASE_ADDR
jmp     _start

; =============================================================================
; 常量定义
; =============================================================================
LOADER_BASE_ADDR equ 0x900                        ; loader程序加载到内存0x900位置
KERNEL_BASE_ADDR equ 0x9000                       ; 内核加载到内存0x9000位置

; =============================================================================
; 全局描述符表 (GDT) - 保护模式的核心数据结构
; GDT是保护模式下管理内存段的关键表格，每个段都有自己的描述符
; 文档: https://wiki.osdev.org/Global_Descriptor_Table
; =============================================================================
LABEL_GDT:          Descriptor 0,       0,          0            ; 空描述符（必须存在）
LABEL_DESC_CODE:    Descriptor 0,       0xFFFFF,    DA_CR | DA_32 | DA_LIMIT_4K  ; 代码段：32位，可执行，4KB粒度，界限0xFFFFF
LABEL_DESC_DATA:    Descriptor 0,       0xFFFFF,    DA_DRW | DA_32 | DA_LIMIT_4K ; 数据段：32位，可读写，4KB粒度，界限0xFFFFF
LABEL_DESC_VIDEO:   Descriptor 0xB8000, 0xFFFF,     DA_DRW                       ; 显存段：基址0xB8000，界限0xFFFF，可读写

GDT_LEN          equ $ - LABEL_GDT                ; GDT的总长度

; =============================================================================
; 段选择子 - 用于在保护模式下选择GDT中的段描述符
; 选择子其实就是段描述符在GDT中的偏移量
; 文档: https://wiki.osdev.org/Segment_Selector
; =============================================================================
SelectorCode     equ LABEL_DESC_CODE  - LABEL_GDT ; 代码段选择子
SelectorData     equ LABEL_DESC_DATA  - LABEL_GDT ; 数据段选择子
SelectorVideo    equ LABEL_DESC_VIDEO - LABEL_GDT ; 显存段选择子

; =============================================================================
; GDT指针 - LGDT指令需要的数据结构，包含GDT长度和基地址
; 格式：前2字节是界限(长度-1)，后4字节是基地址
; 文档: https://wiki.osdev.org/LGDT
; =============================================================================
GdtPtr:
    dw GDT_LEN - 1 ; GDT界限（长度-1）
    dd 0           ; GDT基地址（运行时计算）

; =============================================================================
; 内存检测相关常量
; 使用BIOS的0xE820中断来检测系统内存布局
; 文档: https://wiki.osdev.org/Detecting_Memory_(x86)
; =============================================================================
ARDS_BUFFER     equ 0x5000 ; ARDS(Address Range Descriptor Structure)缓冲区地址
ARDS_COUNT_ADDR equ 0x4FFC ; 存储ARDS数量的地址

; =============================================================================
; 主程序入口 - loader的核心逻辑
; 负责初始化环境、加载内核、进入保护模式
; =============================================================================
_start:
    ; =========================================================================
    ; 初始化段寄存器 - 设置实模式下的内存环境
    ; 在实模式下，所有段寄存器都指向同一个内存区域（平坦模式）
    ; =========================================================================
    mov ax, cs    ; CS是代码段寄存器，指向当前代码位置
    mov ds, ax    ; DS: 数据段，用于访问数据
    mov es, ax    ; ES: 扩展段，用于字符串操作
    mov ss, ax    ; SS: 堆栈段，用于堆栈操作
    mov sp, 0x900 ; SP: 堆栈指针，设置在0x900位置（loader代码末尾）
    
    ; 显示加载信息
    mov  si, msg_loading
    call print
    
    ; =========================================================================
    ; 检测系统内存布局 - 获取可用内存信息供内核使用
    ; 这步很重要，内核需要知道系统有多少内存可用
    ; =========================================================================
    call detect_memory
    
    ; 显示内存检测完成信息
    mov  si, msg_memory_detected
    call print
    
    ; =========================================================================
    ; 从磁盘加载内核到内存 - 将内核代码从硬盘读入内存
    ; 内核存储在硬盘的第2扇区开始（第0扇区是MBR，第1扇区是loader）
    ; =========================================================================
    mov  ebx, 2                ; 起始LBA地址：从第3个扇区开始（LBA从0开始计数）
    mov  cx,  32               ; 要读取的扇区数量：32个扇区 = 16KB
    mov  di,  KERNEL_BASE_ADDR ; 目标内存地址：0x9000
    call read_disk             ; 调用磁盘读取函数

    ; =========================================================================
    ; 初始化GDT并进入保护模式 - 从实模式切换到保护模式
    ; 这是loader的核心任务，保护模式提供了更好的内存保护和更大的寻址空间
    ; =========================================================================
    call gdt_init             ; 初始化全局描述符表
    call enter_protected_mode ; 执行保护模式切换
    
    ; 如果执行到这里说明出错了，无限循环
    jmp $

; =============================================================================
; GDT初始化函数 - 设置全局描述符表
; GDT定义了保护模式下的内存段布局，这里使用平坦内存模型
; 文档: https://wiki.osdev.org/GDT_Tutorial
; =============================================================================
gdt_init:
    ; =========================================================================
    ; 设置代码段描述符 - 配置代码段基地址为0（平坦模式）
    ; 在平坦模式下，代码可以访问整个4GB内存空间
    ; =========================================================================
    mov eax,                   0  ; 代码段基地址设为0
    mov [LABEL_DESC_CODE + 2], ax ; 设置段基址的低16位（描述符偏移+2位置）
    shr eax,                   16 ; 右移16位，获取高16位
    mov [LABEL_DESC_CODE + 4], al ; 设置段基址的中间8位
    mov [LABEL_DESC_CODE + 7], ah ; 设置段基址的高8位
    
    ; =========================================================================
    ; 设置数据段描述符 - 配置数据段基地址为0（平坦模式）
    ; =========================================================================
    mov eax,                   0  ; 数据段基地址设为0
    mov [LABEL_DESC_DATA + 2], ax ; 设置段基址的低16位
    shr eax,                   16 ; 右移16位，获取高16位
    mov [LABEL_DESC_DATA + 4], al ; 设置段基址的中间8位
    mov [LABEL_DESC_DATA + 7], ah ; 设置段基址的高8位
    
    ; =========================================================================
    ; 计算并设置GDT指针 - GDT可能不在内存0地址，需要计算实际地址
    ; GDT存储在loader代码中，需要用段地址+偏移量计算线性地址
    ; =========================================================================
    mov eax,                cs        ; 获取代码段的值
    shl eax,                4         ; 左移4位：段地址转换为线性地址（段地址 * 16）
    add eax,                LABEL_GDT ; 加上GDT在段内的偏移量
    mov dword [GdtPtr + 2], eax       ; 设置GDT指针中的基地址字段
    ret

; =============================================================================
; 进入保护模式函数 - 执行实模式到保护模式的切换
; 这是操作系统开发中最关键的步骤之一，需要严格按照顺序执行
; 文档: https://wiki.osdev.org/Protected_Mode
; =============================================================================
enter_protected_mode:
    ; 显示正在进入保护模式的信息
    mov  si, msg_protected_mode
    call print
    
    ; =========================================================================
    ; 关闭中断 - 保护模式切换期间不能被中断打断
    ; 中断处理机制在保护模式和实模式下完全不同
    ; =========================================================================
    cli ; 清除中断标志位(IF)，禁止中断
    
    ; =========================================================================
    ; 加载GDT - 告诉CPU GDT在哪里
    ; LGDT指令将GDT指针加载到GDTR寄存器
    ; =========================================================================
    lgdt [GdtPtr] ; 加载全局描述符表
    
    ; =========================================================================
    ; 开启A20地址线 - 解决实模式下的地址回绕问题
    ; 在实模式下，地址超过1MB会回绕到0地址，A20线控制这个行为
    ; 文档: https://wiki.osdev.org/A20_Line
    ; =========================================================================
    in  al,   0x92 ; 读取端口0x92的当前值（系统控制端口A）
    or  al,   2    ; 设置第1位（A20使能位）
    out 0x92, al   ; 写回端口，开启A20线
    
    ; =========================================================================
    ; 设置CR0.PE位 - 正式开启保护模式
    ; CR0是控制寄存器，PE位(Protection Enable)控制是否进入保护模式
    ; =========================================================================
    mov eax, cr0 ; 读取当前CR0值
    or  eax, 1   ; 设置PE位（第0位）
    mov cr0, eax ; 写回CR0，开启保护模式
    
    ; =========================================================================
    ; 远跳转刷新流水线 - 强制CPU清空预取的实模式指令
    ; 这是必要的，因为CPU的指令预取队列中可能还有实模式指令
    ; 文档: https://wiki.osdev.org/Protected_Mode#Entering_Protected_Mode
    ; =========================================================================
    jmp dword SelectorCode:protected_mode_entry ; 远跳转到保护模式代码

; =============================================================================
; 字符串打印函数 - 在实模式下显示文本到屏幕
; 使用BIOS的0x10中断的0x0E功能输出字符
; 参数：SI = 要打印的字符串地址（以0结尾）
; 文档: https://wiki.osdev.org/Text_Mode_Cursor
; =============================================================================
print:
    mov ah, 0x0E ; BIOS视频服务：显示字符功能
.loop:
    lodsb        ; 从SI指向的内存加载字节到AL，并SI++
    test  al, al ; 检查是否是字符串结束符(0)
    jz    .done  ; 如果是0，跳转到结束
    int   0x10   ; 调用BIOS视频中断，显示AL中的字符
    jmp   .loop  ; 继续打印下一个字符
.done:
    ret ; 函数返回

[bits 32]
; =============================================================================
; 保护模式入口点 - 32位保护模式下的初始化代码
; 从这里开始就是32位代码，可以访问完整的4GB内存空间
; =============================================================================
protected_mode_entry:
    ; =========================================================================
    ; 设置保护模式下的段寄存器 - 初始化所有段选择子
    ; 在保护模式下，每个段寄存器都指向GDT中的段描述符
    ; =========================================================================
    mov ax, SelectorData ; 数据段选择子
    mov ds, ax           ; DS: 数据段
    mov es, ax           ; ES: 扩展段
    mov fs, ax           ; FS: 额外的数据段
    mov gs, ax           ; GS: 额外的数据段
    mov ss, ax           ; SS: 堆栈段
    
    ; =========================================================================
    ; 设置堆栈指针 - 在保护模式下重新设置堆栈
    ; 堆栈设置在0x8000，避免与内核代码(0x9000开始)冲突
    ; =========================================================================
    mov esp, 0x8000 ; ESP: 扩展堆栈指针，32位模式下的堆栈指针
    
    ; =========================================================================
    ; 传递内存检测信息给内核 - loader检测的内存信息存储在固定地址
    ; 内核可以通过这些地址获取内存布局信息
    ; =========================================================================
    ; ARDS_COUNT_ADDR (0x4FFC): 存储ARDS条目数量
    ; ARDS_BUFFER (0x5000): 存储ARDS数据结构数组
    
    ; =========================================================================
    ; 跳转到内核 - 将控制权交给内核代码
    ; 内核代码从0x9000地址开始执行
    ; =========================================================================
    jmp dword SelectorCode:KERNEL_BASE_ADDR ; 远跳转到内核入口点

[bits 16]
; =============================================================================
; 磁盘读取函数 - 从硬盘读取数据到内存
; 使用ATA PIO模式读取硬盘扇区，支持LBA寻址
; 参数：
;   EBX = 起始LBA地址（扇区号）
;   CX = 要读取的扇区数量
;   DI = 目标内存地址
; 返回：无
; 文档: https://wiki.osdev.org/ATA_PIO_Mode
; =============================================================================
read_disk:
    ; =========================================================================
    ; 设置要读取的扇区数量 - 发送到ATA控制器的扇区计数端口
    ; =========================================================================
    mov dx, 0x1F2 ; ATA扇区计数端口(0x1F2)
    mov al, cl    ; AL = 扇区数量（CL寄存器的低8位）
    out dx, al    ; 发送扇区数量到控制器
    
    ; =========================================================================
    ; 设置LBA地址 - LBA地址需要分4个字节发送到不同的端口
    ; LBA = Logical Block Address，逻辑块地址
    ; =========================================================================
    mov dx, 0x1F3 ; LBA低8位端口
    mov al, bl    ; AL = LBA的低8位
    out dx, al    ; 发送LBA[7:0]
    
    mov dx, 0x1F4 ; LBA中8位端口
    mov al, bh    ; AL = LBA的次低8位
    out dx, al    ; 发送LBA[15:8]
    
    mov dx,  0x1F5 ; LBA高8位端口
    mov eax, ebx   ; EAX = 完整的LBA地址
    shr eax, 16    ; 右移16位，获取高16位中的低8位
    mov al,  al    ; AL = LBA[23:16]
    out dx,  al    ; 发送LBA[23:16]
    
    mov dx, 0x1F6 ; 设备/磁头端口
    mov al, 0xE0  ; 设置LBA模式、主硬盘、LBA[27:24]
    out dx, al    ; 发送设备选择和LBA高4位
    
    ; =========================================================================
    ; 发送读取命令 - 告诉硬盘控制器开始读取操作
    ; =========================================================================
    mov dx, 0x1F7 ; 命令端口
    mov al, 0x20  ; READ SECTORS命令(0x20)
    out dx, al    ; 发送读取命令
    
    ; =========================================================================
    ; 等待硬盘准备好 - 轮询状态端口直到数据就绪
    ; =========================================================================
.wait:
    in   al, dx   ; 读取状态端口
    test al, 0x80 ; 检查BSY位(第7位)是否为1(忙)
    jnz  .wait    ; 如果忙，继续等待
    test al, 0x08 ; 检查DRQ位(第3位)是否为1(数据就绪)
    jz   .wait    ; 如果未就绪，继续等待
    
    ; =========================================================================
    ; 读取数据 - 从数据端口读取所有扇区的数据
    ; 每个扇区512字节，ATA每次传输一个字(2字节)
    ; =========================================================================
    mov ax, cx ; AX = 扇区数量
    shl ax, 8  ; 左移8位：扇区数 * 256 = 总字数(扇区数 * 512 / 2)
    mov cx, ax ; CX = 要读取的总字数
    
    mov dx, 0x1F0 ; 数据端口(0x1F0)
    mov bx, di    ; BX = 目标内存地址
.read_loop:
    in   ax,   dx   ; 从数据端口读取一个字(2字节)
    mov  [bx], ax   ; 存储到内存
    add  bx,   2    ; 内存地址+2
    loop .read_loop ; 循环直到所有数据读取完毕
    
    ret ; 函数返回

; =============================================================================
; 内存检测函数 - 使用BIOS中断检测系统内存布局
; 调用BIOS的0x15中断的0xE820功能，获取内存地址范围描述符(ARDS)
; 返回的ARDS信息存储在ARDS_BUFFER中，供内核使用
; 文档: https://wiki.osdev.org/Detecting_Memory_(x86)#BIOS_Function:_INT_0x15.2C_EAX_.3D_0xE820
; =============================================================================
detect_memory:
    xor ebx,                     ebx         ; EBX必须初始化为0（第一次调用时）
    mov edi,                     ARDS_BUFFER ; EDI = ARDS缓冲区地址（存储ARDS结构的数组）
    mov edx,                     0x534d4150  ; EDX = "SMAP"签名（BIOS要求）
    mov dword [ARDS_COUNT_ADDR], 0           ; 初始化ARDS计数器为0
    
.next_ards:
    ; ========================================================================
    ; 调用BIOS中断 - 请求下一个ARDS条目
    ; ========================================================================
    mov eax, 0xE820 ; EAX = 功能号0xE820
    mov ecx, 20     ; ECX = ARDS结构大小(20字节)
    int 0x15        ; 调用BIOS中断0x15
    
    ; ========================================================================
    ; 检查是否成功 - CF位表示调用结果
    ; ========================================================================
    jc .error ; 如果CF置位，说明出错
    
    ; ========================================================================
    ; 验证BIOS返回值 - 确保返回的是有效的ARDS
    ; ========================================================================
    cmp eax, 0x534d4150 ; 检查返回值是否是"SMAP"
    jne .error          ; 如果不是，说明出错
    
    ; ========================================================================
    ; 保存ARDS条目 - 增加计数器
    ; ========================================================================
    inc dword [ARDS_COUNT_ADDR] ; ARDS数量+1
    
    ; ========================================================================
    ; 准备下一次调用 - 移动到缓冲区的下一个位置
    ; ========================================================================
    add edi, 20 ; EDI += 20，指向下一个ARDS位置
    
    ; ========================================================================
    ; 检查是否还有更多ARDS - EBX为0表示这是最后一个
    ; ========================================================================
    cmp ebx, 0     ; 检查EBX是否为0
    jne .next_ards ; 如果不为0，继续获取下一个ARDS
    
    ret ; 检测完成，返回

.error:
    ; ========================================================================
    ; 错误处理 - 显示错误信息并停止
    ; ========================================================================
    mov  si, msg_memory_error
    call print
    jmp  $                    ; 死循环，停止执行

; =============================================================================
; 数据区 - 存储常量字符串和消息
; 放在文件末尾，避免被代码覆盖
; =============================================================================
msg_loading         db "Loading kernel...", 13, 10, 0          ; 加载内核消息
msg_protected_mode  db "Entering protected mode...", 13, 10, 0 ; 进入保护模式消息
msg_memory_detected db "Memory detected...", 13, 10, 0         ; 内存检测完成消息
msg_memory_error    db "Memory detection error!", 13, 10, 0    ; 内存检测错误消息